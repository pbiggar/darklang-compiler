let private ids =
    AST.allocateFunctionIds
        [AST.functionId 0UL; AST.functionId 1UL]
        names

let functionIdForName (name: string) : AST.FunctionId =
    match name with
    | "_start" -> AST.functionId 0UL
    | "__dark_compiler_program_entry" -> AST.functionId 1UL
    | _ ->
        Map.tryFind name ids
        |> Option.defaultWith (fun () ->
            Crash.crash $"Fixture function '{name}' has no allocated identity")
